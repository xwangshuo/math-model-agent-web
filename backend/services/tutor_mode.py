ai_service = AIService()


def get_available_modes() -> list[dict]:
    """获取所有可用的导师模式"""
    return [
        {
            "id": info["id"],
            "name": info["name"],
            "description": info["description"],
            "icon": info["icon"],
        }
        for mode, info in TUTOR_SYSTEM_PROMPTS.items()
    ]


def get_system_prompt(mode_id: str) -> str:
    """根据 mode_id 获取对应的系统提示词"""
    for mode, info in TUTOR_SYSTEM_PROMPTS.items():
        if info["id"] == mode_id:
            return info["system_prompt"]
    return TUTOR_SYSTEM_PROMPTS["建模教练"]["system_prompt"]


def tutor_chat(
    message: str,
    history: list,
    mode: str,
    context: str = "",
) -> str:
    """以指定导师角色进行对话"""
    system_prompt = get_system_prompt(mode)

    if context:
        system_prompt += f"\n\n## 当前问题上下文\n{context}\n"

    return ai_service.chat(
        message,
        history,
        max_tokens=2048,
        system_prompt=system_prompt,
        use_tools=False,
    )
